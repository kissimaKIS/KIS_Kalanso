# KIS Kalanso distingue plusieurs rôles utilisateurs avec des droits
# différents. Sans ceci, la session reste valable 2 semaines par défaut
# (comportement Django standard) même après fermeture du navigateur : la
# prochaine personne à relancer l'application reprendrait la session (et
# donc les droits) du dernier utilisateur connecté, ce qui viderait la
# distinction des rôles de son sens. La session expire donc à la fermeture
# du navigateur ; voir aussi launcher.py, qui purge toutes les sessions à
# chaque démarrage de l'application pour garantir une reconnexion à chaque
# lancement, même si le navigateur restaure l'onglet précédent.
SESSION_EXPIRE_AT_BROWSER_CLOSE = True



